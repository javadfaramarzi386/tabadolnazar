"""
مدیریت پنل ادمین جنگو - اپلیکیشن accounts

هدف فایل:
    این فایل مدل‌های اپلیکیشن accounts را در پنل مدیریت Django ثبت می‌کند
    و نحوه نمایش، جستجو، فیلتر و مرتب‌سازی آن‌ها را برای ادمین سایت مشخص می‌نماید.

مدل‌های ثبت شده:
    1. Profile     → اطلاعات تکمیلی کاربران
    2. Report      → گزارش‌های تخلف و نظرات کاربران

مزایا:
    - مدیریت آسان کاربران و گزارش‌ها بدون نیاز به کد اضافی
    - جستجوی سریع، فیلتر پیشرفته و نمایش مرتب اطلاعات
"""

from django.contrib import admin
from .models import Profile, Report


# =============================================================================
# مدیریت مدل Profile
# =============================================================================

@admin.register(Profile)
class ProfileAdmin(admin.ModelAdmin):
    """
    تنظیمات نمایش و مدیریت مدل Profile در پنل ادمین.

    این کلاس تمام ویژگی‌های نمایش، جستجو و فیلتر پروفایل کاربران را تعریف می‌کند.
    """

    # =========================================================================
    # ستون‌های نمایش داده شده در لیست پروفایل‌ها
    # =========================================================================
    list_display = (
        'user',                # کاربر اصلی
        'nickname',            # نام نمایشی
        'child_age',           # سن فرزند
        'condition_type',      # نوع وضعیت
        'location',            # محل سکونت
        'show_bio',            # آیا بیوگرافی نمایش داده شود
        'created_at',          # تاریخ ایجاد
    )

    # =========================================================================
    # فیلدهایی که در نوار جستجو قابل جستجو هستند
    # =========================================================================
    search_fields = (
        'user__username',      # جستجو در نام کاربری
        'user__email',         # جستجو در ایمیل
        'nickname',
        'location',
        'condition_type',
    )

    # =========================================================================
    # فیلترهای سمت راست پنل (برای محدود کردن نتایج)
    # =========================================================================
    list_filter = (
        'show_bio',
        'show_child_age',
        'show_condition_type',
        'show_location',
        'created_at',
    )

    # =========================================================================
    # ترتیب پیش‌فرض نمایش
    # =========================================================================
    ordering = ('-created_at',)   # جدیدترین‌ها اول نمایش داده شوند

    # =========================================================================
    # فیلدهایی که در صفحه ویرایش به صورت لیست قابل ویرایش هستند (اختیاری)
    # =========================================================================
    # list_editable = ('nickname', 'location', 'show_bio')
    # =============================================================================
    # نکات آموزشی و بهترین شیوه‌ها (برای توسعه‌دهندگان)
    # =============================================================================
    """
    نکات مهم برای توسعه‌دهندگان:

    1. list_display:
       فقط فیلدهایی را اضافه کنید که واقعاً نیاز به مشاهده سریع دارند.
       فیلدهای رابطه‌ای (مثل user) را می‌توانید با متدهای سفارشی نمایش دهید.

    2. search_fields:
       برای فیلدهای رابطه‌ای از "__" استفاده کنید (user__username).

    3. list_filter:
       فیلترهای BooleanField و DateField بسیار کاربردی هستند.

    4. بهینه‌سازی‌های آینده:
       - استفاده از raw_id_fields برای فیلدهای ForeignKey با داده زیاد
       - تعریف actions (عملیات گروهی) مثل تأیید دسته‌ای پروفایل‌ها
       - استفاده از inlines برای نمایش گزارش‌های مرتبط با هر پروفایل
       - اضافه کردن readonly_fields برای فیلدهای حساس

    5. امنیت:
       حتماً در production فیلدهای حساس را از list_display و search_fields حذف کنید.
    """