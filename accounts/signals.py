"""
سیگنال‌های اپلیکیشن accounts

این فایل شامل سیگنال‌های Django است که به صورت خودکار
در زمان وقوع رویدادهای خاص (مانند ایجاد کاربر) اجرا می‌شوند.
"""

from django.db.models.signals import post_save
from django.dispatch import receiver

from django.contrib.auth.models import User
from .models import Profile


# =============================================================================
# ایجاد و ذخیره خودکار پروفایل کاربر
# =============================================================================

@receiver(post_save, sender=User)
def create_user_profile(sender, instance, created, **kwargs):
    """
    ایجاد خودکار پروفایل برای کاربر جدید.

    این سیگنال بلافاصله بعد از ایجاد یک کاربر جدید (User) اجرا می‌شود
    و یک رکورد Profile مرتبط با آن کاربر می‌سازد.

    مزیت:
        - نیازی به ایجاد دستی پروفایل در فرم ثبت‌نام نیست.
        - اطمینان از وجود پروفایل برای تمام کاربران.
    """
    if created:
        Profile.objects.create(user=instance)


@receiver(post_save, sender=User)
def save_user_profile(sender, instance, **kwargs):
    """
    ذخیره پروفایل هنگام ذخیره تغییرات کاربر.

    این سیگنال هر بار که یک کاربر ذخیره می‌شود اجرا می‌شود
    و اطمینان حاصل می‌کند که تغییرات احتمالی پروفایل نیز ذخیره شوند.

    نکته ایمنی:
        از hasattr استفاده شده تا اگر به هر دلیلی پروفایل وجود نداشت،
        خطا رخ ندهد (مخصوصاً در زمان ایجاد سوپریوزر یا عملیات اولیه).
    """
    if hasattr(instance, 'profile'):
        instance.profile.save()


# =============================================================================
# نکات آموزشی و بهترین شیوه‌ها
# =============================================================================
"""
نکات مهم درباره سیگنال‌ها:

1. post_save:
   - بعد از ذخیره موفق رکورد در دیتابیس اجرا می‌شود.
   - پارامتر `created` مشخص می‌کند رکورد جدید است یا بروزرسانی.

2. sender=User:
   - سیگنال فقط برای مدل User فعال می‌شود.

3. عملکرد در production:
   - سیگنال‌ها باید سبک باشند.
   - از عملیات سنگین (مثل ارسال ایمیل) در سیگنال اجتناب کنید
     مگر اینکه از Celery استفاده کنید.

4. نحوه فعال‌سازی:
   - این فایل باید در apps.py داخل متد ready() import شود.
"""